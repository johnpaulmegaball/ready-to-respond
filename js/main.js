// =========================================================
// Ready to Respond — HOSA Community Awareness Campaign
// Two small jobs:
//   1. Toggle the mobile nav menu open/closed
//   2. Fade/slide elements with the "reveal" class into view as the
//      visitor scrolls past them, falling back to showing everything
//      immediately if IntersectionObserver isn't available
// =========================================================

document.addEventListener("DOMContentLoaded", function () {
  // ---- 1. Mobile nav toggle ----
  var toggle = document.getElementById("navToggle");
  var nav = document.getElementById("mainNav");

  if (toggle && nav) {
    toggle.addEventListener("click", function () {
      var isOpen = nav.classList.toggle("is-open");
      toggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
    });

    nav.querySelectorAll("a").forEach(function (link) {
      link.addEventListener("click", function () {
        nav.classList.remove("is-open");
        toggle.setAttribute("aria-expanded", "false");
      });
    });
  }

  // ---- 2. Scroll-reveal ----
  var revealEls = document.querySelectorAll(".reveal");
  if (!revealEls.length) return;

  if (!("IntersectionObserver" in window)) {
    revealEls.forEach(function (el) { el.classList.add("is-visible"); });
    return;
  }

  var observer = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });

  revealEls.forEach(function (el) { observer.observe(el); });
});
